// Writes src/lib/themes-local-catalog.ts: the metadata of Reed's own themes
// (core, hand-ported and design), so the editor's first screen can list them
// without importing their render code. theme-local-catalog.test.ts fails when
// this file is stale; rerun `npm run gen:local-themes` after editing a theme's
// id, name, desc, category, ui or meta.
import fs from 'node:fs'
import path from 'node:path'
import { catalogEntryOf } from '../../src/lib/theme-meta'
import { CORE_THEMES } from '../../src/lib/themes-core'
import { EXTRA_THEMES } from '../../src/lib/themes-extra'
import { DESIGN_THEMES } from '../../src/lib/themes-design'

const modules = [
  ['core', CORE_THEMES],
  ['extra', EXTRA_THEMES],
  ['design', DESIGN_THEMES],
] as const

const entries = modules.flatMap(([, themes]) => themes.map(catalogEntryOf))
const moduleOf = Object.fromEntries(modules.flatMap(([name, themes]) => themes.map((theme) => [theme.id, name])))

const body = [
  `// AUTO-GENERATED by scripts/themes/local-catalog.ts (npm run gen:local-themes) — do not edit by hand.`,
  `// Metadata of Reed's own themes for the first screen; the render code is`,
  `// loaded on demand by theme-api.ts from the module named in LOCAL_THEME_MODULE.`,
  ``,
  `import type { ThemeCatalogEntry } from './theme-meta'`,
  ``,
  `export type LocalThemeModule = 'core' | 'extra' | 'design'`,
  ``,
  `export const LOCAL_THEME_CATALOG: ThemeCatalogEntry[] = ${JSON.stringify(entries, null, 2)}`,
  ``,
  `export const LOCAL_THEME_MODULE: Readonly<Record<string, LocalThemeModule>> = ${JSON.stringify(moduleOf, null, 2)}`,
  ``,
].join('\n')

const file = path.resolve(process.cwd(), 'src/lib/themes-local-catalog.ts')
fs.writeFileSync(file, body, 'utf8')
console.log(`[local-themes] ${entries.length} entries -> ${path.relative(process.cwd(), file)}`)
